let currentLang = 'ru';

function setLang(lang) {
  if (TRANSLATIONS[lang]) currentLang = lang;
  document.documentElement.lang = currentLang;
}

// Получить перевод по ключу с подстановкой параметров: t('foo.bar', { name: 'X' })
function t(key, params) {
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.ru;
  let str = dict[key] ?? TRANSLATIONS.ru[key] ?? key;
  if (params) {
    for (const k in params) str = str.split(`{${k}}`).join(params[k]);
  }
  return str;
}

// Применить переводы ко всем элементам с data-i18n* атрибутами
function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (el.dataset.i18nHtml === '1') el.innerHTML   = t(key);
    else                              el.textContent = t(key);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.dataset.i18nTitle);
  });
}

window.i18n = { setLang, t, applyTranslations, TRANSLATIONS, getLang: () => currentLang };

